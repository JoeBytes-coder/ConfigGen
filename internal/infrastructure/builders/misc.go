package builders

import (
	corev1 "k8s.io/api/core/v1"
	schedulingv1 "k8s.io/api/scheduling/v1"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"

	"configgen/internal/domain"
)

func init() {
	register("PriorityClass", buildPriorityClass)
	register("Namespace", buildNamespace)
}

func buildPriorityClass(app domain.AppContext, n domain.Node) (any, error) {
	return &schedulingv1.PriorityClass{
		TypeMeta:      metav1.TypeMeta{APIVersion: "scheduling.k8s.io/v1", Kind: "PriorityClass"},
		ObjectMeta:    metav1.ObjectMeta{Name: n.Name, Labels: labels(app)},
		Value:         1000,
		GlobalDefault: false,
		Description:   "Priority class generated by ConfigGen",
	}, nil
}

func buildNamespace(app domain.AppContext, n domain.Node) (any, error) {
	return &corev1.Namespace{
		TypeMeta:   metav1.TypeMeta{APIVersion: "v1", Kind: "Namespace"},
		ObjectMeta: metav1.ObjectMeta{Name: n.Name, Labels: labels(app)},
	}, nil
}
